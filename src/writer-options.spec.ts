import { generateNotes } from '@semantic-release/release-notes-generator';
import { describe, expect, it } from 'vitest';

import { writerOpts as writerOptions } from './writer-options.ts';

import type { GenerateNotesContext } from 'semantic-release';

const preset = 'conventionalcommits';

const createContext = (): GenerateNotesContext =>
  ({
    commits: [
      { hash: 'a1b2c3d', message: 'feat(cli): add /copy slash command' },
      { hash: 'b2c3d4e', message: 'fix: correct typo in readme' },
      {
        hash: 'c3d4e5f',
        message:
          'feat!: drop legacy config\n\nBREAKING CHANGE: legacy config is removed',
      },
    ],
    cwd: process.cwd(),
    lastRelease: { gitHead: 'a1b2c3d', gitTag: 'v1.0.0' },
    nextRelease: { gitHead: 'c3d4e5f', gitTag: 'v2.0.0', version: '2.0.0' },
    options: {
      repositoryUrl: 'https://github.com/unlight/changelog-sentence-case.git',
    },
  }) as unknown as GenerateNotesContext;

const generate = (options: Record<string, unknown>) =>
  generateNotes({ preset, ...options }, createContext());

describe('writerOpts', () => {
  it('is a plain object with a finalizeContext hook', () => {
    expect(writerOptions.finalizeContext).toBeTypeOf('function');
  });

  it('only carries finalizeContext, so preset options survive', () => {
    expect(Object.keys(writerOptions)).toEqual(['finalizeContext']);
  });

  it('sentence-cases subjects in notes generated by the standard generator', async () => {
    const notes = await generate({ writerOpts: writerOptions });

    expect(notes).toContain('Add /copy slash command');
    expect(notes).toContain('Correct typo in readme');
    expect(notes).not.toContain('* add /copy slash command');
  });

  it('keeps scope and section grouping from the preset', async () => {
    const notes = await generate({ writerOpts: writerOptions });

    expect(notes).toContain('**cli:** Add /copy slash command');
    expect(notes).toMatch(/### Features/);
    expect(notes).toMatch(/### Bug Fixes/);
  });

  it('leaves breaking change notes as authored', async () => {
    const notes = await generate({ writerOpts: writerOptions });

    expect(notes).toContain('legacy config is removed');
  });

  it('never renders the commit type as text', async () => {
    const notes = await generate({ writerOpts: writerOptions });

    expect(notes).toContain('* Correct typo in readme');
    expect(notes).not.toContain('fix:');
    expect(notes).not.toContain('Fix:');
  });

  it('has no effect when the hook is not passed', async () => {
    const notes = await generate({});

    expect(notes).toContain('* **cli:** add /copy slash command');
  });
});
